CREATE UNIQUE INDEX IF NOT EXISTS students_id_uidx ON students (id);

CREATE TABLE IF NOT EXISTS instructor (
    instructorname VARCHAR(50) PRIMARY KEY,
    description VARCHAR(150),
    carnr INTEGER
);

CREATE TABLE IF NOT EXISTS course (
    course_id INTEGER PRIMARY KEY,
    startdate VARCHAR(50),
    price INTEGER
);

CREATE TABLE IF NOT EXISTS instructor_history (
    history_id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    student_id INTEGER NOT NULL REFERENCES students(id) ON DELETE CASCADE,
    instructorname VARCHAR(50),
    hours INTEGER NOT NULL DEFAULT 0
);
